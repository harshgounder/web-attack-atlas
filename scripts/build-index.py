#!/usr/bin/env python3
"""build-index.py: one index across every wave, so the write suite reads as a system."""
import json, glob
from collections import Counter, defaultdict
from pathlib import Path
R = Path(__file__).resolve().parent.parent
rows = []
for f in sorted(glob.glob(str(R/"waves"/"*"/"patterns.jsonl"))):
    for l in open(f):
        if l.strip():
            p = json.loads(l); p["_wave"] = Path(f).parent.name; rows.append(p)
atoms = json.load(open(R/"data"/"atoms.json")); AN = {a["id"]: a["name"] for a in atoms["atoms"]}
cc = json.load(open(R/"data"/"control-classes.json"))["classes"]
q = json.load(open(R/"waves"/"QUEUE.json")); TITLE = {d["id"]: d["title"] for d in q["domains"]}

L = ["# Index", "", "Generated by `scripts/build-index.py`. One view across every wave.", "",
     f"**{len(rows)} patterns** in **{len({r['_wave'] for r in rows})} waves**, "
     f"{len({a for r in rows for a in r['atom']})} atoms, "
     f"{len({r['counter']['control_class'] for r in rows})} control classes.", "",
     "## By domain", "", "| wave | domain | patterns | states |", "|---|---|---|---|"]
byw = defaultdict(list)
for r in rows: byw[r["_wave"]].append(r)
for w in sorted(byw):
    st = Counter(r["status"] for r in byw[w])
    L.append(f"| {w} | {TITLE.get(w,w)} | {len(byw[w])} | " + ", ".join(f"{k} {v}" for k, v in st.items()) + " |")

L += ["", "## Atom matrix", "",
      "Rows are the 16 primitives, columns are the write domains. A cell is how many patterns there use",
      "that atom. This is the view that shows whether a domain really stresses a different primitive.",
      "", "| atom | " + " | ".join(sorted(byw)) + " | total |",
      "|---|" + "---|" * (len(byw) + 1)]
for aid in AN:
    cells = [sum(1 for r in byw[w] if aid in r["atom"]) for w in sorted(byw)]
    if sum(cells) == 0: continue
    L.append(f"| `{aid}` {AN[aid]} | " + " | ".join(str(c) if c else "-" for c in cells) + f" | **{sum(cells)}** |")

L += ["", "## By control class", "", "| class | control | patterns |", "|---|---|---|"]
byc = defaultdict(list)
for r in rows: byc[r["counter"]["control_class"]].append(r)
for cid, ps in sorted(byc.items(), key=lambda kv: -len(kv[1])):
    L.append(f"| {cid} | {cc.get(cid,{}).get('name',cid)} | {len(ps)} |")

L += ["", "## All patterns", "", "| id | pattern | atoms | persists |", "|---|---|---|---|"]
for r in sorted(rows, key=lambda x: x["id"]):
    L.append(f"| `{r['id']}` | {r['title']} | {','.join(r['atom'])} | {r['persistence'][:40]} |")

L += ["", "## Reading the suite as one system", "",
      "The three write domains answer three different questions about the same act:", "",
      "1. **W01** asks *what does the write do to the record's lifecycle*. Identity, versioning, concurrency,",
      "   cascade, restore, roundtrip. The bug is in the mechanics.",
      "2. **W02** asks *whose data is it*. Ownership, tenancy, role, field level, delegation. The bug is in",
      "   the permission model.",
      "3. **W03** asks *where does the value come out later*. Renderers, queues, exports, mail, caches.",
      "   The bug is in the sink.",
      "", "A single request can violate all three at once, and that composition is where real impact lives:",
      "write into someone else's object (W02), from a value that will be rendered in an operator console",
      "(W03), using a partial update that also clears a protected field (W01). No single domain sees it."]
(R/"INDEX.md").write_text("\n".join(L) + "\n")
print(f"INDEX.md: {len(rows)} patterns, {len(L)} lines")
